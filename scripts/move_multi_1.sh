#!/bin/bash

set -e

#######################################
# 配置
#######################################
DST_BASE="/Volumes/HD2/mirror"
LOG_FILE="$HOME/move_multi.log"

DRY_RUN=false
FORCE=false

#######################################
# 日志函数
#######################################
log() {
  echo -e "$1" | tee -a "$LOG_FILE"
}

run_cmd() {
  if $DRY_RUN; then
    log "🧪 [DRY-RUN] $*"
  else
    log "▶️ 执行: $*"
    eval "$@"
  fi
}

#######################################
# 参数解析
#######################################
ARGS=()

while [[ "$#" -gt 0 ]]; do
  case "$1" in
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    --force)
      FORCE=true
      shift
      ;;
    *)
      ARGS+=("$1")
      shift
      ;;
  esac
done

if [ "${#ARGS[@]}" -lt 1 ]; then
  echo "用法: $0 [--dry-run] [--force] <目录1> <目录2> ..."
  exit 1
fi

#######################################
# 检查目标路径
#######################################
if [ ! -d "$DST_BASE" ]; then
  log "❌ 目标路径不存在或未挂载: $DST_BASE"
  exit 1
fi

log "📦 目标根目录: $DST_BASE"
log "📝 日志文件: $LOG_FILE"
log "🧪 DRY_RUN: $DRY_RUN | FORCE: $FORCE"
log "----------------------------------"

#######################################
# 主逻辑
#######################################
for SRC in "${ARGS[@]}"; do
  log ""
  log "👉 处理: $SRC"

  SRC=$(realpath "$SRC")

  #######################################
  # 基本检查
  #######################################
  if [ ! -d "$SRC" ]; then
    log "⚠️ 不存在，跳过"
    continue
  fi

  if [ -L "$SRC" ]; then
    log "⚠️ 已是软链接，跳过"
    continue
  fi

  #######################################
  # ✅ 映射策略（版本1：去掉开头 /）
  #######################################
  REL_PATH="${SRC#/}"
  DST="$DST_BASE/$REL_PATH"

  log "源目录: $SRC"
  log "目标目录: $DST"

  #######################################
  # 目标冲突处理
  #######################################
  if [ -e "$DST" ]; then
    if $FORCE; then
      log "⚠️ 目标已存在，--force 删除: $DST"
      run_cmd rm -rf "\"$DST\""
    else
      log "⚠️ 目标已存在，跳过（可用 --force 覆盖）"
      continue
    fi
  fi

  #######################################
  # 创建父目录
  #######################################
  DST_PARENT=$(dirname "$DST")
  run_cmd mkdir -p "\"$DST_PARENT\""

  #######################################
  # rsync（包含隐藏文件 ✔）
  #######################################
  log "🚚 rsync 迁移中..."
  run_cmd rsync -a --progress "\"$SRC/\"" "\"$DST/\""

  #######################################
  # 备份原目录
  #######################################
  BACKUP="${SRC}_backup_$(date +%Y%m%d%H%M%S)"
  log "📦 备份原目录 -> $BACKUP"
  run_cmd mv "\"$SRC\"" "\"$BACKUP\""

  #######################################
  # 创建软链接
  #######################################
  log "🔗 创建软链接..."
  run_cmd ln -s "\"$DST\"" "\"$SRC\""

  #######################################
  # 验证
  #######################################
  if [ -L "$SRC" ]; then
    log "✅ 完成: $SRC -> $DST"
    log "🧹 可稍后删除备份: $BACKUP"
  else
    log "❌ 失败，恢复中..."
    run_cmd mv "\"$BACKUP\"" "\"$SRC\""
  fi

  log "----------------------------------"
done

log ""
log "🎉 所有任务处理完成！"